import fs from 'node:fs';
import { facilityCosts } from '../packages/domain/dist/finance/facility-costs.js';
import { projectTicketDemand, TICKET_TIERS } from '../packages/domain/dist/finance/match-demand.js';
import { stadiumBenefits } from '../packages/domain/dist/finance/stadium-benefits.js';
const data = JSON.parse(fs.readFileSync('data/player-database.json', 'utf8'));
const baselines = {};
const economics = [];
for (const club of Object.values(data.clubs.byId)) {
  const stadium = data.stadiums.byId[club.stadiumId];
  const marketing = data.centers.byId[club.trainingCenterId].levels.marketing;
  const expenses =
    club.playerIds.reduce((sum, id) => sum + data.players.byId[id].salary.cents, 0) +
    facilityCosts(data, club).reduce((sum, item) => sum + item.cost, 0);
  const normal = projectTicketDemand(
    {
      capacity: stadium.sectors.reduce((sum, sector) => sum + sector.capacity, 0),
      commerce: stadiumBenefits(stadium).commerce,
      selloutPriceCents: TICKET_TIERS[0].priceCents,
      minimumCrowdPriceCents: TICKET_TIERS[3].priceCents,
      demandFactor: 1,
    },
    TICKET_TIERS[1].priceCents,
  );
  const commerce =
    Math.round((normal.consumptionRevenue * (marketing >= 4 ? 1.2 : 1)) / 10000) * 10000;
  economics.push({
    club,
    expenses,
    marketing,
    ticket: normal.ticketRevenue * 2,
    commerce: commerce * 2,
  });
}
for (const { club, expenses, marketing, ticket, commerce } of economics) {
  const opponents = economics.filter(
    ({ club: other }) =>
      other.id !== club.id && other.country === club.country && other.division === club.division,
  );
  const awayGate = opponents.length
    ? opponents.reduce((sum, other) => sum + other.ticket, 0) / opponents.length
    : ticket;
  const monthlyGate = ticket * 0.7 + awayGate * 0.3 + commerce;
  baselines[club.id] = [
    Math.max(0, Math.ceil((expenses * 1.15 - monthlyGate) / 4 / 10000) * 10000),
    marketing,
  ];
}
fs.writeFileSync(
  'packages/domain/src/finance/sponsorship-baselines.ts',
  '// Generated by scripts/generate-sponsorship-baselines.mjs from initial club economics.\nexport const SPONSORSHIP_BASELINES: Readonly<Record<string, readonly [number, number]>> = ' +
    JSON.stringify(baselines, null, 2) +
    ';\n',
);
