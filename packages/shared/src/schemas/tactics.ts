export const FORMATIONS = Object.fromEntries(
  formationSchema.options.map((name) => [
    name,
    layouts[name].slots.map(([position, x, y]) => ({ position, x, y })),
  ]),
) as Record<Formation, Array<{ position: Position; x: number; y: number }>>;
export const FORMATION_LINKS = Object.fromEntries(
  formationSchema.options.map((name) => [name, layouts[name].links]),
) as Record<Formation, Array<[number, number]>>;
export const playStyleSchema = z.enum([
  'balanced',
  'wings',
  'gegenpress',
  'all-out-press',
  'low-block',
  'possession',
  'counter',
]);
export type PlayStyle = z.infer<typeof playStyleSchema>;
export const matchInstructionsSchema = z.strictObject({
  substitutions: z
    .array(
      z.strictObject({
        out: entityIdSchema,
        in: entityIdSchema,
        when: z.union([
          z.literal(60),
          z.literal(70),
          z.literal(80),
          z.literal(90),
          z.literal('fatigue'),
        ]),
        score: z.enum(['always', 'winning', 'drawing', 'losing']),
      }),
    )
    .max(3)
    .refine(
      (plans) =>
        new Set(plans.map((p) => p.out)).size === plans.length &&
        new Set(plans.map((p) => p.in)).size === plans.length,
      'Não repita jogadores nas trocas',
    ),
  protected: z.array(entityIdSchema).max(2),
  situations: z
    .array(
      z.strictObject({
        trigger: z.enum(['winning-two', 'losing-60', 'drawing-75']),
        style: playStyleSchema.optional(),
        formation: formationSchema.optional(),
      }),
    )
    .max(3)
    .refine(
      (rules) => new Set(rules.map((r) => r.trigger)).size === rules.length,
      'Não repita situações',
    ),
});
export type MatchInstructions = z.infer<typeof matchInstructionsSchema>;
export const lineupSchema = z.strictObject({
  instructions: matchInstructionsSchema.optional(),
  bench: z
    .array(entityIdSchema)
    .max(12)
    .refine((ids) => new Set(ids).size === ids.length, 'O banco contém atletas repetidos')
    .optional(),
  style: playStyleSchema.optional(),
  formation: formationSchema,
  starters: z
    .array(entityIdSchema)
    .length(11)
    .refine((ids) => new Set(ids).size === 11, 'A escalação contém atletas repetidos'),
});
export type Lineup = z.infer<typeof lineupSchema>;
export const lineupPresetSchema = z.strictObject({
  id: entityIdSchema,
  name: z.string().trim().min(1).max(40),
  lineup: lineupSchema,
});
